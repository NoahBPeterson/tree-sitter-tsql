static const int KEYWORD_COUNT = sizeof(KEYWORDS) / sizeof(KEYWORDS[0]);

/* Case-insensitive strcmp: returns <0, 0, >0 like strcmp */
static int ci_strcmp(const char *a, const char *b) {
  while (*a && *b) {
    char ca = (*a >= 'a' && *a <= 'z') ? *a - 32 : *a;
    char cb = (*b >= 'a' && *b <= 'z') ? *b - 32 : *b;
    if (ca != cb) return ca - cb;
    a++;
    b++;
  }
  /* Handle different lengths */
  unsigned char ua = (*a >= 'a' && *a <= 'z') ? *a - 32 : *a;
  unsigned char ub = (*b >= 'a' && *b <= 'z') ? *b - 32 : *b;
  return ua - ub;
}

/* Binary search on sorted KEYWORDS array */
static int is_keyword(const char *word) {
  int lo = 0, hi = KEYWORD_COUNT - 1;
  while (lo <= hi) {
    int mid = lo + (hi - lo) / 2;
    int cmp = ci_strcmp(word, KEYWORDS[mid]);
    if (cmp == 0) return 1;
    if (cmp < 0) hi = mid - 1;
    else lo = mid + 1;
  }
  return 0;
}

static int is_id_start(int32_t c) {
  return (c >= 'A' && c <= 'Z') ||
         (c >= 'a' && c <= 'z') ||
         c == '_' || c == '#';
}

static int is_id_continue(int32_t c) {
  return is_id_start(c) ||
         (c >= '0' && c <= '9') ||
         c == '$' || c == '@';
}

/* --- Required tree-sitter external scanner API --- */

/* ASCII-order strcmp for keyword sort verification (uppercase compare) */
static int ascii_strcmp(const char *a, const char *b) {
  while (*a && *b) {
    if ((unsigned char)*a != (unsigned char)*b)
      return (unsigned char)*a - (unsigned char)*b;
    a++;
    b++;
  }
  return (unsigned char)*a - (unsigned char)*b;
}

void *tree_sitter_TSQL_external_scanner_create(void) {
  /* Verify KEYWORDS array is sorted on first use */
  for (int i = 1; i < KEYWORD_COUNT; i++) {
    if (ascii_strcmp(KEYWORDS[i - 1], KEYWORDS[i]) >= 0) {
      fprintf(stderr,
        "tree-sitter-tsql: KEYWORDS sort error at index %d: \"%s\" >= \"%s\"\n",
        i, KEYWORDS[i - 1], KEYWORDS[i]);
      abort();
    }
  }
  return NULL;  /* stateless scanner */
}

void tree_sitter_TSQL_external_scanner_destroy(void *payload) {
  /* nothing to free */
}

unsigned tree_sitter_TSQL_external_scanner_serialize(void *payload, char *buffer) {
  return 0;  /* no state to serialize */
}

void tree_sitter_TSQL_external_scanner_deserialize(void *payload, const char *buffer, unsigned length) {
  /* no state to restore */
}

bool tree_sitter_TSQL_external_scanner_scan(
    void *payload, TSLexer *lexer, const bool *valid_symbols) {

  if (!valid_symbols[NON_KEYWORD_ID]) {
    return false;
  }

  /* Skip whitespace */
  while (lexer->lookahead == ' ' || lexer->lookahead == '\t' ||
         lexer->lookahead == '\r' || lexer->lookahead == '\n') {
    lexer->advance(lexer, true);
  }

  /* Check if current char can start an identifier */
  if (!is_id_start(lexer->lookahead)) {
    return false;
  }

  /* Let TEMP_ID_ handle #-prefixed identifiers (temp tables/procs) */
  if (lexer->lookahead == '#') {
    return false;
  }

  /* Read the full identifier into a buffer */
  char buffer[256];
  int length = 0;

  while (is_id_continue(lexer->lookahead) && length < 255) {
    buffer[length++] = (char)lexer->lookahead;
    lexer->advance(lexer, false);
  }
  buffer[length] = '\0';

  /* Reject if it's ANY grammar keyword */
  if (is_keyword(buffer)) {
    return false;
  }

  lexer->result_symbol = NON_KEYWORD_ID;
  return true;
}
