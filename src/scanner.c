/**
 * External scanner for tree-sitter-tsql.
 *
 * Provides a _non_keyword_id token that matches the identifier pattern
 * [A-Za-z_#][A-Za-z_#$@0-9]* but REJECTS all T-SQL grammar keywords.
 *
 * This prevents the word: property from demoting keywords (like FROM,
 * SELECT, WHERE, AVG, COUNT) into identifiers. Non-reserved keywords
 * that are allowed as identifiers (like STATUS, TYPE, NAME) are handled
 * separately by the _keyword rule in grammar.js.
 *
 * Uses binary search on a sorted keyword table for O(log n) lookup.
 */

